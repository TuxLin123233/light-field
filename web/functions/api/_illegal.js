/* 需要「搭配出现」才判定的形式。
   单看「转账」「出售」「微信」这类词，正常聊天里也会出现（比如「我微信联系你」），
   一律拦会误伤。所以只在和交易动词共现时才拦。 */
const PATTERNS = [
  /(出售|低价出|高价收|收购|转让|代购)[^\n]{0,8}(账号|装备|作品|作品源|数据|源码|图纸)/,
  /(微信|qq|vx|扣扣|企鹅)[^\n]{0,6}(转账|付款|支付|发红包|打钱)/i,
  /(加|扫)[^\n]{0,4}(二维码|收款码)/,
  /(私|线)[^\n]{0,3}(下|外)[^\n]{0,3}(交易|付款|转账|成交)/,
  /(日入|月入|躺赚|稳赚)[^\n]{0,6}(元|块|w|万)/i,
  /(兼职|刷单)[^\n]{0,6}(日结|高薪|轻松|无门槛)/,
]

/** 归一化：去掉空白和常见分隔符，避免「加 微 信」这种拆字绕过 */
function norm(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/[\s\u200b\u200c\u200d\u2060.,，。、·\-_~!！?？*＊#＃@＠+＋=＝^&%$'"“”‘’()（）[\]【】{}<>《》/\\|]/g, '')
}

/**
 * 查违法交易 / 引流内容。
 * @returns {string[]} 命中的词（已去重），空数组表示没问题
 */
export function hitTrade(text) {
  const raw = String(text || '')
  const n = norm(raw)
  if (!n) return []
  const hit = []
  for (const w of WORDS) {
    if (n.includes(norm(w))) hit.push(w)
  }
  for (const re of PATTERNS) {
    const m = raw.match(re)
    if (m) hit.push(m[0].slice(0, 12))
  }
  return [...new Set(hit)]
}

/** 只要一个「有没有」的答案 */
export function hasTrade(text) {
  return hitTrade(text).length > 0
}
